% regression(infile,outfile,form,method,soilmethod,mech,mechanism,figures)
% INFILE=Name of file containing filenames of files with spectral values
% OUTFILE=Name of output file containing coefficients to produce
% FORM=1, ..., 9:
%                           1 implies log y=b1+b2 M+b3 log(sqrt(d^2+b5^2))+b4 (sqrt(d^2+b5^2))
%                           2 implies log y=b1+b2 M+b3 log(sqrt(d^2+b4^2))
%                           3 implies log y=b1+b2 M+b3 M^2+b4 log(sqrt(d^2+b6^2))+b5 (sqrt(d^2+b6^2))
%                           4 implies log y=b1+b2 M+b3 M^2+b4 log(sqrt(d^2+b5^2))
%                           5 implies log y=b1+b2 log(sqrt(d^2+b4^2))+b3 (sqrt(d^2+b4^2))
%                           6 implies log y=b1+b2 log(sqrt(d^2+b3^2))
%                           7 implies log y=b1+b2 M-log(sqrt(d^2+b4^2))+b3(sqrt(d^2+b4^2))
%                           8 implies log y=b1+b2 M+b3 log(d+b4)
%                           9 implies log y=b1+b2 M+b3 M^2+b4*R+b5*log10(R+b6*10^(b7*M)
%                          10 implies log y=b1+b2 M+b3 d
%                          11 implies ln y=b1+b2 M+b3 (8.5-M)^2+b4 ln (sqrt(d^2+(b7 exp (b8 M))^2))+
%                                     (c5+c6 M)d +f3(d)
%                                     where f3(d)=0 for d<=r1
%                                           f3(d)=c9(ln d-ln r1) for r1<d<=r2
%                                           f3(d)=c9(ln d-ln r1)+c10 (ln d-ln r2) for d>r2
%
%
% Routine to calculate the spectral attenuation coefficients for all the dampings
% and periods stated in the input files.
%
% Required input file is INFILE which consists of a list of files
% generated by SPECATT.FOR. It sends these filenames to routine NLREGL.M
% which calculates the corresponding coefficients and returns them to this
% routine.
%
% N.B. New coefficients are appended to the end of file so need to
% delete old OUTFILEs unless want the new coefficients appended to
% end
%
% Can use ATTEN_PLT.M or PGA_PLT.M to plot results
%
% Author: J. Douglas
%
% History:
% -  2. 7.1999: Created
% -  2. 7.1999: Documented
% -  9. 8.1999: Added "both" variable
% - 25.10.1999: Changed to output matrix C and the number of datapoints
%				and coefficients found
% - 26.10.1999: Added lines to output header and changed to output a few new
%			    statistics.
% -  1.11.1999: Added depth option.
% -  2.11.1999: Corrected a problem with outputting when both horizontal and
%               vertical periods.
% -  3.11.1999: Documented depth option.
% -  1. 3.2001: Did some tidying up. Deleted redundant lines.
% -  1. 3.2001: Updated documentation.
% -  6. 1.2003: Improved structure and extendability of program.
% - 10. 1.2003: Started including soil coefficient calculation
% - 17. 1.2003: Improved outputting of results so that column labels match
%               with contents of column
% - 20. 1.2003: Added lines to output standard errors of all coefficients
% - 21. 1.2003: Implemented calculation of soil coefficients using method
%               (2)
% - 22. 1.2003: Implemented calculation of soil coefficients using method
%               (1) for all regression methods but 5.
% -  4.11.2003: Changed regression.m to create regressionhybrid.m for use
%               with files from CHEEP
% -  5.11.2003: Added Campbell (2003)'s functional form
%
% Last revision:  5.11.2003
