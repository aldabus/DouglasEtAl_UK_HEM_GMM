tic

% Loop to calculate coefficients
[b,sd,seb,sig,dper,N,nc]=nlregl(str2num(char(period)),infile,form,branch);
neq=1;
nst=1;
nsd=length(sd);
ssd=['     sd1'];
ssdn=[' %7.4f '];
for l=1:nsd-1;
    ssd=[ssd,'      sd',num2str(l+1)];
    ssdn=[ssdn,' %7.4f '];
end
sb='';
sse='';
ss=' ';
sbn='';
ssen='';
ssn='';
for l=1:nc;
    sb=[sb,'        b',num2str(l),' '];
    sbn=[sbn,' %12.8f '];
    sse=[sse,'       se',num2str(l)];
    ss=[ss,' ',num2str(l),' '];
    ssen=[ssen,' %8.5f '];
    ssn=[ssn,' %1i '];
end

% Outputting to file
% Checking if new file if so outputs header
filename=[outfile,num2str(branch,'%1i'),'.txt'];
fid1=fopen(filename,'rt');
if fid1==-1
    newfile=1;
else
    newfile=0;
    fclose(fid1);
end
fid1 = fopen(filename,'at');
if newfile==1
    fprintf(fid1,['%1i %1i %2i %2i \n'],[form,1,-1,-1]);
    fprintf(fid1,['%s \n'],['Damp  Period',sb,ssd,sse,ss,'   N  Neq  Nst  c']);
end
fprintf(fid1,['%4.1f %7.4f',sbn,ssdn,ssen,ssn,'%4i %4i %4i %2i \n'],dper(1),dper(2),b,sd,seb,sig,N,neq,nst,nc);
fclose(fid1);

