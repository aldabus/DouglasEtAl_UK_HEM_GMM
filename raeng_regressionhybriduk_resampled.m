function [theta,sd,Varb,fh,nc]=linnlreg(Y,xi,n,theta,nc,acc,func1)
% ---------------------------------------------------------------------
% [theta,sd,Varb,fh]=linnlreg(Y,xi,n,theta,nc,acc,func1)
% Input:
% Y=n x 1 vector of measured accelerations
% xi=n x nc vector of (magnitudes and) distances
% n=number of data points
% theta=starting values of coefficients
% nc=number of coefficients
% acc=accuracy to achieve in coefficients
% func1=function name for functional form to use
%
% Output:
% theta=least squares coefficients
% sd=standard deviation
% Varb=approximate variance-covariance matrix
% fh=estimated accelerations
%
% Function to apply Marquardt's method (as implemented by Osborne (1972))
% for nonlinear regression. Uses a two step orthogonal factorization to
% improve efficiency.
%
% References:
% "Nonlinear Regression", Gallant, A.R. The American Statistician,
% Number 2, Volume 29, May 1975, pp. 73-81.
%
% "Some Aspects of Non-linear Least Squares Calculations", Osborne, M.R. in
% Numerical Methods for Non-linear Optimization, edited by Lootsma, F.A.,1972
% pp. 171-190.
%
% Author: J. Douglas
%
% History:
% - 18.10.1999: Created
% - 19.10.1999: Implemented two-step method
% - 20.10.1999: Improved efficiency slightly
% - 22.10.1999: Corrected a couple of mistakes and added alternative two-step
% -  1.11.1999: Added depth option.
% -  3.11.1999: Documented depth option.
% -  6. 1.2003: Improved structure and extendiability by using eval
% -  9. 1.2003: Changed to use feval rather than eval because about 4 times
%               faster
% - 20. 1.2003: Added lines to calculate standard errors of all coefficients
% - 22. 1.2003: Implemented calculation of soil coefficients using method
%               (1).
%
% Last revision: 22. 1.2003
% ----------------------------------------------------------------------------

f=zeros(1,n);
Z=zeros(n,nc);

% Increase factor for nu if another step has to be calculated
EXP=1.5;
% Decrease factor for nu if except current step
DECR=0.5;
% Reset count (if no convergence after 1000 steps then aborts calculation)
count=1;
% Reset sum of squares
ss=0;
% Loop to calculate initial derivative matrix and nu value
for i=1:n
    [f0,Z(i,1:nc)]=feval(func1,xi(i,:),theta(1:nc));
    ss=ss+sum(Z(i,1:nc).^2);
end

nu=sqrt(ss/(n*nc));
% Main loop repeats until convergence (or 1000 loops) is reached
b=ones(1,nc);
while(and(max(norm(b,inf))>acc,count<1000))
    % If not first step then calculates new derivate matrix
    if count>1
        for i=1:n
            [f0,Z(i,1:nc)]=feval(func1,xi(i,:),theta(1:nc));
        end
    end
    % First step of orthogonalization of derivative matrix
    [Q1,R1]=qr(Z,0);
    % Loop repeats until exceptable step is found
    ic=0;
    nf=1;
    nfh=nf+1;
    while(nfh>nf)
        % Second step of orthogonalization
        temp=[R1;zeros(1,nc);nu*eye(nc)];
        [Q2,R]=qr(temp,0);
        % Calculate new derivative matrix and function vector
        for i=1:n
            [f(i),Z(i,1:nc)]=feval(func1,xi(i,:),theta(1:nc));
        end
        nf=norm(Y-f,2);
        % Calculating step vector
        b=R'*R\(Z'*(Y-f)');
        % Calculating function vector with new coefficients
        for i=1:n
            [fh(i),z0]=feval(func1,xi(i,:),theta(1:nc)+b(1:nc));
        end
        nfh=norm(Y-fh,2);
        ic=ic+1;
        % Checking see whether new step is an improvement, if is not then increases
        % nu and repeats
        if(nfh>nf)
            nu=nu*EXP;
        end
    end
    % Updating coefficients vector
    theta=theta+b;
    % If first calculated step was exceptable then decreases nu
    if ic==1
        nu=nu*DECR;
    end
    count=count+1;
end

% Calculating standard deviation
sd=sqrt(nfh^2/(n-nc));
% Calculating co-variance matrix of coefficients
Varb=inv(Z'*Z)*sd^2;
